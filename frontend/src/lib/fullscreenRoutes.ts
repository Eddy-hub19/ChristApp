/**
 * Маршрути повноекранних ігор: навбар і перемикач теми там не рендеряться взагалі (а не лише перекриваються).
 * Це працює з першого кадру — навіть до завантаження коду самої гри (вона підтягується динамічно) і після
 * перезавантаження. Нова повноекранна гра в `/games/<назва>` потрапляє сюди автоматично.
 * Гру, що відкривається модалкою поверх іншого екрана, ховає навбар через `useFullscreenMode(open)`.
 */
export function isFullscreenPath(pathname: string | null | undefined): boolean {
  const p = (pathname ?? "").replace(/\/+$/, "");
  return p.startsWith("/games/");
}
